def generate(
    *,
    repo_root: Path,
    out_dir: Path,
    channels: tuple[str, ...],
    curation_tag: str = "",
) -> dict[str, ChannelResult]:
    """Build every requested channel and write the site into *out_dir*."""
    entries = read_registry(repo_root / "registry")
    if not entries:
        raise MarketplaceError(f"{repo_root / 'registry'} holds no entries — nothing to publish")

    locks: dict[str, Lock | None] = {"edge": None}
    for channel in ("stable", "latest"):
        if channel in channels:
            locks[channel] = read_lock(repo_root / "locks" / f"{channel}.toml")

    results: dict[str, ChannelResult] = {}
    out_dir.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory() as tmp:
        work_dir = Path(tmp)
        for channel in channels:
            lock = locks.get(channel)
            result = build_channel(entries, channel, lock, work_dir=work_dir)
            results[channel] = result

            header = _FEED_HEADER.format(
                channel=channel,
                blurb=_CHANNEL_BLURB[channel],
                url=f"{BASE_URL}/{channel}/marketplace.toml",
            )
            body = emit_feed(result.rows, header=header)

            channel_dir = out_dir / channel
            channel_dir.mkdir(parents=True, exist_ok=True)
            (channel_dir / "marketplace.toml").write_text(body, encoding="utf-8")

            # Archive the pinned channels under their curation tag. `edge` is
            # never archived: its specs float, so an "immutable" edge archive
            # would be a promise the channel cannot keep.
            if curation_tag and channel in ("stable", "latest") and lock is not None:
                stamp = (
                    f"# archived: {curation_tag} {date.today().isoformat()} "
                    f"haywire-core={lock.framework.get('haywire-core', 'unknown')}\n"
                )
                archive_dir = channel_dir / curation_tag
                archive_dir.mkdir(parents=True, exist_ok=True)
                (archive_dir / "marketplace.toml").write_text(stamp + body, encoding="utf-8")

    (out_dir / "index.html").write_text(render_index(results), encoding="utf-8")
    (out_dir / "archives.html").write_text(render_archives(collect_archives(out_dir)), encoding="utf-8")

    report = repo_root / "stable-report.md"
    if report.is_file():
        shutil.copyfile(report, out_dir / "stable-report.md")

    # Pages runs Jekyll by default, which drops files and directories whose
    # names begin with an underscore and can rewrite what it thinks is content.
    # Nothing here is a Jekyll site.
    (out_dir / ".nojekyll").write_text("", encoding="utf-8")

    return results


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="generate_feed",
        description="Generate the curated marketplace's published feeds and pages.",
    )
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument(
        "--channel",
        action="append",
        choices=CHANNELS,
        help="Generate only this channel (repeatable). Default: all three.",
    )
    parser.add_argument(
        "--curation-tag",
        default="",
        help="Write immutable archives for stable/latest under this tag.",
    )
    parser.add_argument(
        "--strict",
        action="store_true",
        help="Exit non-zero if any library failed to build a row (used by deploy).",
    )
    args = parser.parse_args(argv)

    channels = tuple(args.channel) if args.channel else CHANNELS

    try:
        results = generate(
            repo_root=args.repo_root,
            out_dir=args.out_dir,
            channels=channels,
            curation_tag=args.curation_tag,
        )
    except MarketplaceError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    failed = False
    for channel in channels:
        result = results[channel]
        print(f"{channel}: {len(result.rows)} rows -> {args.out_dir / channel / 'marketplace.toml'}", file=sys.stderr)
        for name, reason in result.failures:
            failed = True
            print(f"  ! {name}: {reason}", file=sys.stderr)

    return 1 if failed and args.strict else 0


if __name__ == "__main__":
    sys.exit(main())
