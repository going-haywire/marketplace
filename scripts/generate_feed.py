"""Generate the published site: three channel feeds, archives, and the pages.

    uv run python scripts/generate_feed.py --out-dir _site
    uv run python scripts/generate_feed.py --out-dir _site --channel edge

Reads `registry/*.toml` plus the locks, and for each member: resolves the wheel
URL from the PyPI JSON API, downloads it, unzips it, reads the `haybale.toml`
inside, and builds a row. Every field comes from that artifact.

**This script never imports a downloaded package.** It runs in the privileged
tier — the one with `contents: write` that deploys Pages — so it must have no
reason to execute submitted code. Reading metadata out of a wheel is unzipping;
that is what makes the split possible. The load gate that *does* import lives
in `verify.yml`, which has `permissions: {}` and no secrets.

Output under `--out-dir`:

    index.html                              the three channels, what each asserts
    edge/marketplace.toml
    latest/marketplace.toml
    stable/marketplace.toml
    stable/<curation-tag>/marketplace.toml  immutable archive
    latest/<curation-tag>/marketplace.toml  immutable archive
    archives.html                           the archive index
    stable-report.md                        copied from the repo root when present
"""

from __future__ import annotations

import argparse
import shutil
import sys
import tempfile
from dataclasses import dataclass
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from emit import emit_feed  # noqa: E402
from haywire.core.library.haybale import Haybale  # noqa: E402
from marketplace_lib import (  # noqa: E402
    CHANNELS,
    Lock,
    MarketplaceError,
    RegistryEntry,
    build_row,
    download_wheel,
    fetch_all_releases,
    fetch_release,
    newest_version,
    read_lock,
    read_registry,
    read_wheel_metadata,
    verify_row_version,
)

BASE_URL = "https://going-haywire.github.io/marketplace"

_CHANNEL_BLURB = {
    "edge": "whatever is newest on PyPI right now. Regenerated nightly.",
    "latest": "the newest version of each library as of the last catalogue release, "
    "each proven to install and load on its own.",
    "stable": "versions proven to install and load *together* as one set. Advances when Haywire cuts a release.",
}

_FEED_HEADER = """\
# The Haywire curated marketplace — {channel} channel
#
# {blurb}
#
# Generated by scripts/generate_feed.py. Do not edit by hand: this file is
# rebuilt from registry/*.toml on every deploy and any edit is discarded.
#
# Subscribe by pasting this URL into Add Source in the studio's Library
# Browser:
#   {url}
#
# Every field in every row below was read out of the wheel it pins. Nothing
# here is authored by a curator. Being listed asserts that the distribution
# exists on PyPI, that this name maps to this distribution, and — for stable —
# that this version resolves alongside the rest of the set. It asserts nothing
# about whether the code is safe, correct, or maintained. Nobody reads the
# source.
"""


@dataclass(frozen=True)
class ChannelResult:
    """One generated channel: its rows, and what could not be built."""

    channel: str
    rows: list[Haybale]
    failures: list[tuple[str, str]]


def _resolve_version(entry: RegistryEntry, channel: str, lock: Lock | None) -> str:
    """Which version of *entry* this channel describes.

    `edge` tracks PyPI directly; the pinned channels take their answer from the
    lock and nowhere else, so a generated feed can never disagree with the set
    that was actually solved and verified.
    """
    if channel == "edge":
        return newest_version(fetch_all_releases(entry.name))
    if lock is None:
        raise MarketplaceError(f"channel {channel!r} needs a lock")
    version = lock.pins.get(entry.name)
    if not version:
        # Not an error: a library can be in the registry and legitimately not
        # in `stable` yet — it may have failed to fit. stable-report.md is
        # where that is explained.
        raise KeyError(entry.name)
    return version


def build_channel(
    entries: list[RegistryEntry],
    channel: str,
    lock: Lock | None,
    *,
    work_dir: Path,
) -> ChannelResult:
    """Build every row for one channel by reading each pinned wheel."""
    rows: list[Haybale] = []
    failures: list[tuple[str, str]] = []

    for entry in entries:
        try:
            version = _resolve_version(entry, channel, lock)
        except KeyError:
            continue  # Not in this channel's set; see stable-report.md.
        except MarketplaceError as exc:
            failures.append((entry.name, str(exc)))
            continue

        try:
            release = fetch_release(entry.name, version)
            if not release.wheel_url:
                raise MarketplaceError(
                    f"{entry.name} {version} has no wheel on PyPI. Row metadata is read out of "
                    f"a wheel; building an sdist to read it would mean executing its setup."
                )
            if release.yanked:
                raise MarketplaceError(
                    f"{entry.name} {version} is yanked"
                    + (f": {release.yanked_reason}" if release.yanked_reason else "")
                )
            wheel = download_wheel(release.wheel_url, work_dir / f"{entry.name}-{version}.whl")
            metadata = read_wheel_metadata(wheel, entry.name)
            if not metadata.declares_library_entry_point:
                raise MarketplaceError(
                    f"{entry.name} {version} declares no `haywire.libraries` entry point — "
                    f"a studio could install it but never load it."
                )
            row = build_row(metadata, dist_name=entry.name, version=version, channel=channel)
            verify_row_version(row, metadata)
            rows.append(row)
        except MarketplaceError as exc:
            failures.append((entry.name, str(exc)))

    return ChannelResult(channel=channel, rows=rows, failures=failures)


